/**
 * Running sheet apps over **data** (phase 24, 24.2.32).
 *
 * The five apps (`ts/ss` × `send`/`receive`/`summary`) keep using
 * `SheetHandlerBase` and the `FileStore` interface (ADR 037) —
 * **demoted, not revoked**: callers driving them step by step (PWA/F19) inject
 * the persistent store. At the `execute` boundary no disk is involved: this
 * module seeds a {@link MemoryFileStore} with the request files, runs the app
 * and returns the result as **data** (`files`, `emails`, `attachments`, `log`).
 *
 * So `requireFileStore` stops being a caller requirement: the store always
 * exists, but it is ephemeral and the consumer decides what to persist (the
 * CLI writes it through `io.ts`, 24.10).
 *
 * @see docs/syntaxmesh/decisoes/037-filestore-injection.md
 * @see docs/syntaxmesh/fases/fase-24-cli-adendo.md §3.5
 */

import {
  MemoryFileStore,
  type MemoryStoreFile,
} from "../interfaces/memory-file-store.ts";
import type { Project, } from "../model/project.ts";
import type { SheetAppBase, } from "./apps/app-base.ts";
import type { EmailMessage, } from "./email-message.ts";
import type { SheetLogEntry, } from "./sheet-handler-base.ts";

/** Input/output file of the data path (`request.files`). */
export type SheetDataFile = MemoryStoreFile;

/** Attachment returned by a sender/receiver — already materialized as text. */
export interface SheetDataAttachment {
  /** Attachment name (`dev_2026-05-18.tji`). */
  name: string;
  /** UTF-8 contents of the attachment. */
  contents: string;
}

/**
 * App input on the data path.
 *
 * `files` is the set of reads: whatever the app would open from disk enters
 * here (templates, `resources.json`, signatures, `all.tji`). `dirs` creates
 * empty folders the flow expects to find (for instance the period folder).
 */
export interface SheetAppData {
  /** Files visible to the app (they seed the `MemoryFileStore`). */
  files?: readonly SheetDataFile[];
  /** Directories that must exist before the app runs. */
  dirs?: readonly string[];
  /** RFC 822 text received (receivers) — data, not a file. */
  rawEmail?: string | null;
}

/** App output on the data path — everything is a value, nothing is an effect. */
export interface SheetAppDataResult {
  /** `0` success · `1` failure (same matrix as `SheetAppBase#run`). */
  exitCode: number;
  /** Messages built by `sendEmail`, in emission order. */
  emails: EmailMessage[];
  /** Attachments of the messages, materialized as `{name, contents}`. */
  attachments: SheetDataAttachment[];
  /** Final store (artifacts generated by the app), ordered by path. */
  files: SheetDataFile[];
  /** In-memory log of the handler (`SheetHandlerBase#logEntries`). */
  log: SheetLogEntry[];
}

/**
 * Runs a sheet app with data as input and output.
 *
 * `MessageHandler` remains the diagnostics channel (the `execute` serializes
 * it and turns it into `messages`); no text is printed here.
 */
export async function runSheetAppData(
  app: SheetAppBase,
  project: Project,
  data: SheetAppData = {},
): Promise<SheetAppDataResult> {
  const store = new MemoryFileStore([...(data.files ?? []),],);
  for (const dir of data.dirs ?? []) {
    await store.mkdir(dir,);
  }

  const exitCode = await app.run({
    project,
    fileStore: store,
    rawEmail: data.rawEmail ?? null,
  },);

  const handler = app.handler;
  const emails = [...handler.sentMessages,];
  return {
    exitCode,
    emails,
    attachments: collectAttachments(emails,),
    files: store.toFiles(),
    log: [...handler.logEntries,],
  };
}

/** Extracts the already materialized attachments of the messages (no store I/O). */
function collectAttachments(emails: EmailMessage[],): SheetDataAttachment[] {
  const attachments: SheetDataAttachment[] = [];
  for (const email of emails) {
    if (email.attachmentName === null || email.attachment === null) continue;
    attachments.push({
      name: email.attachmentName,
      contents: email.attachment,
    },);
  }
  return attachments;
}
