/**
 * Sheet file extensions (time/status sheets) — single source of truth.
 *
 * Decision 2026-11-07 (plan §1.6, task 24.2.36): SyntaxMesh **writes** `.smx`
 * — templates sent by the sender, sheets archived by the receiver and
 * inclusion files (`all.smx`). The TaskJuggler shape (`.tji`/`all.tji`) is
 * still **recognized on read**, because sheet attachments stay in transit in
 * mailboxes across versions.
 *
 * The module is intentionally neutral: sender, receiver and summary import
 * from here without dragging one's whole pipeline into the other.
 *
 * @see docs/syntaxmesh/fases/fase-24-cli.md (§1.6, tarefa 24.2.36)
 * @see docs/syntaxmesh/decisoes/037-filestore-injection.md (aditamento)
 */
import { baseName, } from "./email-message.ts";

/** Native extension of the sheet files. */
export const SHEET_EXTENSION = ".smx";

/** Legacy extension (TaskJuggler) — accepted on read, never generated. */
export const LEGACY_SHEET_EXTENSION = ".tji";

/** Sheet extensions accepted on read: the native one and the legacy one. */
export const SHEET_EXTENSIONS = [
  SHEET_EXTENSION,
  LEGACY_SHEET_EXTENSION,
] as const;

/** Name of the inclusion file generated in every sheet folder. */
export const INCLUSION_FILE = "all.smx";

/** Legacy name of the inclusion file (folders generated by old versions). */
export const LEGACY_INCLUSION_FILE = "all.tji";

/** `true` when the name is a sheet (`.smx` or the legacy `.tji`). */
export function isSheetFileName(name: string,): boolean {
  return SHEET_EXTENSIONS.some((ext,) => name.endsWith(ext,));
}

/** `true` when the name is the inclusion file, native or legacy. */
export function isInclusionFileName(name: string,): boolean {
  const base = baseName(name,);
  return base === INCLUSION_FILE || base === LEGACY_INCLUSION_FILE;
}
