/**
 * HTMLDocument — faithful port of `HTMLDocument.rb` (phase 17.4).
 *
 * Specialization of `XMLDocument` that already starts with the mandatory
 * elements of an HTML document: the `<!DOCTYPE>` (or the XML prolog + XHTML DTD
 * pair for the three historical doctypes), the generation comment and the
 * `<html>` with `xml:lang`/`lang` — plus `xmlns` when it is not HTML5.
 *
 * Behaviours checked against the real Ruby (literal oracle output):
 *   - order of the top-level elements: `[constructor block…, doctype, comment,
 *     <html>]` — the block comes **before** the doctype, because `super(&block)`
 *     is the first statement of `initialize`.
 *   - the comment is `This file has been generated by #{AppConfig.appName}
 *     v#{AppConfig.version}` (in TJ3: `tj3 v3.8.4`).
 *   - an invalid `docType` raises `"Unsupported docType"` **after** the XML
 *     prolog has been pushed (the blob stays in the document).
 *   - `generateHead` returns the `<html>` element (not the `<head>`), because
 *     `XMLElement#<<` returns `self` and the expression is
 *     `@html << HEAD.new { … }`.
 *
 * @see docs/taskjuggler/lib/taskjuggler/HTMLDocument.rb
 * @see docs/syntaxmesh/decisoes/038-substituicao-xml.md
 * @see docs/syntaxmesh/fases/fase-17-html-xml-tarefas.md (17.4)
 */

import { AppConfig, } from "../app-config.ts";
import { XMLBlob, XMLComment, XMLElement, } from "../xml/xml-element.ts";
import { XMLDocument, type XmlDocumentBlock, } from "../xml/xml-document.ts";
import { HEAD, HTML, META, TITLE, } from "./html-elements.ts";

/** The four doctypes accepted by Ruby (`:html5` is the default). */
export type HtmlDocType = "html5" | "strict" | "transitional" | "frameset";

/** A complete HTML document — equivalent to `TaskJuggler::HTMLDocument`. */
export class HTMLDocument extends XMLDocument {
  /** The `<html>` element of the document (`attr_reader :html`). */
  readonly html: XMLElement;

  /**
   * Builds the document with the doctype, the generation comment and the
   * `<html>` element.
   *
   * @param docType HTML flavour; anything but `html5` selects XHTML.
   * @param block Optional callback run before the doctype is appended.
   * @throws Error When `docType` is not one of the four supported values.
   */
  constructor(docType: HtmlDocType = "html5", block?: XmlDocumentBlock,) {
    super(block,);

    if (docType !== "html5") {
      this.append(new XMLBlob('<?xml version="1.0" encoding="UTF-8"?>',),);
      let dtdRef: string;
      let url: string;
      switch (docType) {
        case "strict":
          dtdRef = "Strict";
          url = "http://www.w3.org/TR/xhtml1/DTD/xhtml1-strict.dtd";
          break;
        case "transitional":
          dtdRef = "Transitional";
          url = "http://www.w3.org/TR/xhtml1/DTD/xhtml1-transitional.dtd";
          break;
        case "frameset":
          dtdRef = "Frameset";
          url = "http://www.w3.org/TR/xhtml1/DTD/xhtml1-frameset.dtd";
          break;
        default:
          throw new Error("Unsupported docType",);
      }
      this.append(
        new XMLBlob(
          `<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0 ${dtdRef}//EN" "${url}">`,
        ),
      );
    } else {
      this.append(new XMLBlob("<!DOCTYPE html>",),);
    }
    this.append(
      new XMLComment(
        `This file has been generated by ${AppConfig.appName} v${AppConfig.version}`,
      ),
    );

    const attrs: Record<string, string> = { "xml:lang": "en", lang: "en", };
    if (docType !== "html5") {
      attrs["xmlns"] = "http://www.w3.org/1999/xhtml";
    }
    const html = new HTML(attrs,);
    this.html = html;
    this.append(html,);
  }

  /**
   * Ruby `generateHead(title, metaTags = {}, blob = nil)` — builds the `<head>`
   * with `title`, the two mandatory `meta` tags, the optional `metaTags`
   * (insertion order) and a raw `XMLBlob`, when given.
   *
   * ⚠️ Returns **`this.html`**, not the `<head>`: in Ruby the expression is
   * `@html << HEAD.new { … }` and `XMLElement#<<` returns `self`.
   *
   * @param title Text of the `<title>` element.
   * @param metaTags Extra `<meta name content>` pairs to emit.
   * @param blob Raw markup appended at the end of the `<head>`, or `null`.
   * @returns The `<html>` element the head was appended to.
   */
  generateHead(
    title: string,
    metaTags: Record<string, string> = {},
    blob: string | null = null,
  ): XMLElement {
    this.html.append(
      new HEAD({}, () => {
        const e: XMLElement[] = [
          new TITLE({}, () => title,),
          new META({
            "http-equiv": "Content-Type",
            content: "text/html; charset=utf-8",
          },),
          // Hack inherited from Ruby: forces IE into IE-9 mode.
          new META({ "http-equiv": "X-UA-Compatible", content: "IE=9", },),
        ];
        for (const [name, content,] of Object.entries(metaTags,)) {
          e.push(new META({ name, content, },),);
        }
        if (blob !== null && blob !== undefined) e.push(new XMLBlob(blob,),);
        return e;
      },),
    );
    return this.html;
  }
}
