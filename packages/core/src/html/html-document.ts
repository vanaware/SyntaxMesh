/**
 * HTMLDocument — port fiel de `HTMLDocument.rb` (Fase 17.4).
 *
 * Especialização de `XMLDocument` que já nasce com os elementos obrigatórios
 * de um documento HTML: o `<!DOCTYPE>` (ou o par XML prolog + DTD XHTML nos
 * três doctypes históricos), o comentário de geração e o `<html>` com
 * `xml:lang`/`lang` — e `xmlns` quando não for HTML5.
 *
 * Fidelidades conferidas no Ruby real (saída literal do oracle):
 *   - ordem dos elementos de topo: `[bloco do construtor…, doctype, comentário,
 *     <html>]` — o bloco entra **antes** do doctype, porque `super(&block)` é a
 *     primeira instrução do `initialize`.
 *   - o comentário é `This file has been generated by #{AppConfig.appName}
 *     v#{AppConfig.version}` (na TJ3: `tj3 v3.8.4`).
 *   - `docType` inválido levanta `"Unsupported docType"` **depois** de o
 *     prolog XML ter sido empurrado (o blob fica no documento).
 *   - `generateHead` devolve o elemento `<html>` (e não o `<head>`), porque
 *     `XMLElement#<<` devolve `self` e a expressão é `@html << HEAD.new { … }`.
 *
 * @see docs/taskjuggler/lib/taskjuggler/HTMLDocument.rb
 * @see docs/syntaxmesh/decisoes/038-substituicao-xml.md
 * @see docs/syntaxmesh/fases/fase-17-html-xml-tarefas.md (17.4)
 */

import { AppConfig, } from "../app-config.ts";
import { XMLBlob, XMLComment, XMLElement, } from "../xml/xml-element.ts";
import { XMLDocument, type XmlDocumentBlock, } from "../xml/xml-document.ts";
import { HEAD, HTML, META, TITLE, } from "./html-elements.ts";

/** Os quatro doctypes aceitos pelo Ruby (`:html5` é o default). */
export type HtmlDocType = "html5" | "strict" | "transitional" | "frameset";

/** Documento HTML completo — equivalente ao `TaskJuggler::HTMLDocument`. */
export class HTMLDocument extends XMLDocument {
  /** O elemento `<html>` do documento (`attr_reader :html`). */
  readonly html: XMLElement;

  constructor(docType: HtmlDocType = "html5", block?: XmlDocumentBlock,) {
    super(block,);

    if (docType !== "html5") {
      this.append(new XMLBlob('<?xml version="1.0" encoding="UTF-8"?>',),);
      let dtdRef: string;
      let url: string;
      switch (docType) {
        case "strict":
          dtdRef = "Strict";
          url = "http://www.w3.org/TR/xhtml1/DTD/xhtml1-strict.dtd";
          break;
        case "transitional":
          dtdRef = "Transitional";
          url = "http://www.w3.org/TR/xhtml1/DTD/xhtml1-transitional.dtd";
          break;
        case "frameset":
          dtdRef = "Frameset";
          url = "http://www.w3.org/TR/xhtml1/DTD/xhtml1-frameset.dtd";
          break;
        default:
          throw new Error("Unsupported docType",);
      }
      this.append(
        new XMLBlob(
          `<!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0 ${dtdRef}//EN" "${url}">`,
        ),
      );
    } else {
      this.append(new XMLBlob("<!DOCTYPE html>",),);
    }
    this.append(
      new XMLComment(
        `This file has been generated by ${AppConfig.appName} v${AppConfig.version}`,
      ),
    );

    const attrs: Record<string, string> = { "xml:lang": "en", lang: "en", };
    if (docType !== "html5") {
      attrs["xmlns"] = "http://www.w3.org/1999/xhtml";
    }
    const html = new HTML(attrs,);
    this.html = html;
    this.append(html,);
  }

  /**
   * Ruby `generateHead(title, metaTags = {}, blob = nil)` — monta o `<head>`
   * com `title`, os dois `meta` obrigatórios, os `metaTags` opcionais (ordem de
   * inserção) e um `XMLBlob` cru, se houver.
   *
   * ⚠️ Devolve **`this.html`**, não o `<head>`: no Ruby a expressão é
   * `@html << HEAD.new { … }` e `XMLElement#<<` devolve `self`.
   */
  generateHead(
    title: string,
    metaTags: Record<string, string> = {},
    blob: string | null = null,
  ): XMLElement {
    this.html.append(
      new HEAD({}, () => {
        const e: XMLElement[] = [
          new TITLE({}, () => title,),
          new META({
            "http-equiv": "Content-Type",
            content: "text/html; charset=utf-8",
          },),
          // Gambiarra herdada do Ruby: força o IE para o modo IE-9.
          new META({ "http-equiv": "X-UA-Compatible", content: "IE=9", },),
        ];
        for (const [name, content,] of Object.entries(metaTags,)) {
          e.push(new META({ name, content, },),);
        }
        if (blob !== null && blob !== undefined) e.push(new XMLBlob(blob,),);
        return e;
      },),
    );
    return this.html;
  }
}
