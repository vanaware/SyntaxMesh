/**
 * template-engine — thin wrapper of the Vento engine for the `template` element
 * (phase 23, a TS-only extension; ADR 033).
 *
 * **The only module in the core that imports `ventojs`.** No other file may
 * import the library: whoever needs to render uses `renderTemplate`.
 *
 * Why not `env.runString()`: the `TextParser` FSM is synchronous (the scanner
 * expands `${...}` inside `nextToken()`), while Vento 2.x compiles **every**
 * template into an `async` function. The way out used here is to compile with
 * `env.compile()` — which validates the syntax and returns the generated source
 * in `template.code` — and to run that same code with the
 * `async function __template` header rewritten to `function __template`.
 *
 * The rewrite is safe because the subset of tags used to generate `.tjp`
 * (`{{ }}`, `if`, `for`, `set`, `echo`, pipes) emits no `await`; a body that
 * needs I/O (`include`, `layout`, `for await`) does not pass the synchronous
 * compilation and is reported as `async_tag`. For the synchronous subset the
 * result is **byte-identical** to `env.runString()` (covered by a test in
 * `tests/lexer/template-engine_test.ts`).
 *
 * Autoescape stays **off** (a plan §4.8 guarantee): the output is TaskJuggler,
 * not HTML. The explicit `escape` filter remains available.
 *
 * @see docs/syntaxmesh/fases/fase-23-template.md (§4.3, §4.7, §4.8)
 * @see docs/syntaxmesh/decisoes/033-elemento-template.md
 */
import vento from "vento";

/**
 * Type of the Vento `Environment`. The library does not re-export the class in
 * `mod.js` (only the default `vento(options)`), so we derive it from the factory
 * itself.
 */
type VentoEnvironment = ReturnType<typeof vento>;

/** Data injected into the template context (params + global keys). */
export type TemplateData = Record<string, unknown>;

/** How the rendering failed. */
export type TemplateFailureKind = "syntax" | "runtime" | "async";

/** Successful rendering. */
export interface TemplateRenderSuccess {
  ok: true;
  content: string;
}

/**
 * Failed rendering. `position` is the character offset inside the **template
 * body**; `line`/`column` are 1-based and relative to the body — the caller maps
 * them to the original `.tjp` line.
 */
export interface TemplateRenderFailure {
  ok: false;
  kind: TemplateFailureKind;
  message: string;
  position: number;
  line: number;
  column: number;
}

export type TemplateRenderResult =
  | TemplateRenderSuccess
  | TemplateRenderFailure;

/** Already compiled template: takes the data and returns `{ content }`. */
export type CompiledTemplate = (data: TemplateData,) => { content: string };

/** Headers generated by the Vento 2.x `Environment#compile`. */
const ASYNC_HEADER = "async function __template";
const SYNC_HEADER = "function __template";

/** Limit of compiled bodies kept in the cache (LRU approximated by insertion). */
const CACHE_LIMIT = 256;

/** Converts `position` (offset) into a 1-based line/column of the body. */
export function lineColumnOf(
  source: string,
  position: number,
): [number, number,] {
  let line = 1;
  let column = 1;
  const end = Math.max(0, Math.min(position, source.length,),);
  for (let i = 0; i < end; i++) {
    if (source.charCodeAt(i,) === 10) {
      line++;
      column = 1;
    } else {
      column++;
    }
  }
  return [line, column,];
}

/**
 * Compiles the code generated by Vento (`AsyncFunction` → `Function`).
 * Throws `SyntaxError` when the body depends on `await` (an asynchronous tag).
 */
function makeSyncTemplate(
  code: string,
  env: VentoEnvironment,
): CompiledTemplate {
  const syncSource = code.replace(ASYNC_HEADER, SYNC_HEADER,);
  // `code` is `function anonymous(__env) { return <template>; }` — the outer
  // wrapper takes the Environment and returns the inner template.
  const makeOuter = new Function(`return (${syncSource});`,);
  const outer = makeOuter() as (env: VentoEnvironment,) => CompiledTemplate;
  return outer(env,);
}

/** Vento engine shared by the core (autoescape off). */
export class TemplateEngine {
  private readonly env: VentoEnvironment;
  private readonly cache = new Map<string, CompiledTemplate>();

  constructor() {
    this.env = vento({ autoescape: false, },);
  }

  /**
   * Compiles (with caching) a template body.
   *
   * Returns `{ ok: true, template }` or the syntax/async failure already
   * carrying the position inside the body.
   */
  compile(
    body: string,
  ):
    | { ok: true; template: CompiledTemplate }
    | (TemplateRenderFailure & { ok: false }) {
    const cached = this.cache.get(body,);
    if (cached) return { ok: true, template: cached, };

    let code: string;
    try {
      code = this.env.compile(body,).code;
    } catch (e) {
      return this.failure(e, body, "syntax",);
    }

    let template: CompiledTemplate;
    try {
      template = makeSyncTemplate(code, this.env,);
    } catch (e) {
      // `await` inside a non-async function ⇒ an I/O tag (include/layout/for
      // await).
      const message = e instanceof Error ? e.message : String(e,);
      return {
        ok: false,
        kind: "async",
        message,
        position: 0,
        line: 1,
        column: 1,
      };
    }

    if (this.cache.size >= CACHE_LIMIT) {
      const oldest = this.cache.keys().next();
      if (!oldest.done) this.cache.delete(oldest.value,);
    }
    this.cache.set(body, template,);
    return { ok: true, template, };
  }

  /**
   * Renders `body` with `data`, synchronously.
   *
   * Syntax, asynchronous-tag and runtime errors come back as
   * `TemplateRenderFailure` (no `throw`): the caller translates them into the
   * `MessageHandler` with the `SourceFileInfo` of the original `.tjp`.
   */
  render(body: string, data: TemplateData = {},): TemplateRenderResult {
    const compiled = this.compile(body,);
    if (!compiled.ok) return compiled;

    try {
      const result = compiled.template(data,);
      return { ok: true, content: result.content ?? "", };
    } catch (e) {
      return this.failure(e, body, "runtime",);
    }
  }

  /** Drops the cache (tests/batch use with ephemeral bodies). */
  clearCache(): void {
    this.cache.clear();
  }

  /** Converts a Vento error into a `TemplateRenderFailure`. */
  private failure(
    error: unknown,
    body: string,
    kind: TemplateFailureKind,
  ): TemplateRenderFailure {
    const err = error as { message?: string; position?: number };
    const position = typeof err.position === "number" ? err.position : 0;
    const [line, column,] = lineColumnOf(body, position,);
    return {
      ok: false,
      kind,
      message: err.message ?? String(error,),
      position,
      line,
      column,
    };
  }
}

/** Single instance used by the scanner (and by the tests via `renderTemplate`). */
export const templateEngine = new TemplateEngine();

/** Shortcut: renders a template body without touching the instance. */
export function renderTemplate(
  body: string,
  data: TemplateData = {},
): TemplateRenderResult {
  return templateEngine.render(body, data,);
}
