/**
 * Golden test de serialização XML/HTML (Fase 17.16).
 *
 * Consome `html-xml.golden.json` (oracle `scripts/golden/html-xml.rb`) e
 * reconstrói cada caso com as classes portadas (`src/xml/`, `src/html/`),
 * comparando byte-a-byte. Não há normalização de line endings aqui: as saídas
 * são strings internas (nunca tocam arquivo), e `\n`/indentação **são** a
 * carga útil verificada.
 *
 * Os builders abaixo espelham 1:1 as lambdas do script Ruby — mesma árvore,
 * mesma ordem de `append`, mesmos atributos. Qualquer divergência de bytes do
 * `to_s`/`write('.')` do port quebra o caso correspondente.
 *
 * O comentário "generated by …" do HTMLDocument casa byte-a-byte porque o
 * oracle fixa `AppConfig.appName/version` nos defaults do port
 * (`packages/core/src/app-config.ts`: "syntaxmesh"/`VERSION` de
 * `src/version.ts`, a fonte única desde a 24.6.6).
 *
 * @see scripts/golden/html-xml.rb
 * @see docs/syntaxmesh/fases/fase-17-html-xml-tarefas.md (17.16)
 */
import { describe, it, } from "@std/testing/bdd";
import { assertEquals, } from "@std/assert";
import {
  XMLBlob,
  XMLComment,
  XMLElement,
  XMLNamedText,
  XMLText,
} from "../../src/xml/xml-element.ts";
import { XMLDocument, } from "../../src/xml/xml-document.ts";
import { HTMLDocument, } from "../../src/html/html-document.ts";

interface GoldenCase {
  id: string;
  kind: string;
  spec: Record<string, unknown>;
  expected: string;
}

/** Espelho do `add('ctor_string_child')`: bloco devolve string sola. */
function ctorStringChild(): string {
  return new XMLElement("p", {}, false, () => "Hello",).to_s();
}

function appendChildTree(): string {
  const outer = new XMLElement("div",);
  const inner = new XMLElement("span",);
  inner.append("oi",);
  outer.append(inner,);
  return outer.to_s();
}

function ulWith(items: string[],): string {
  const ul = new XMLElement("ul",);
  for (const t of items) {
    const li = new XMLElement("li",);
    li.append(t,);
    ul.append(li,);
  }
  return ul.to_s();
}

function textAndChild(): string {
  const div = new XMLElement("div",);
  div.append("txt",);
  const b = new XMLElement("b",);
  b.append("bold",);
  div.append(b,);
  return div.to_s();
}

function nilChildIgnored(): string {
  const div = new XMLElement("div",);
  div.append(null,);
  div.append("ok",);
  return div.to_s();
}

function setAttrOperator(): string {
  const img = new XMLElement("img",);
  img.setAttr("src", "a&amp;b.png",);
  img.setAttr("alt", 'quote " inside',);
  return img.to_s();
}

function commentInElement(): string {
  const div = new XMLElement("div",);
  div.append(new XMLComment("oi",),);
  div.append("x",);
  return div.to_s();
}

function blobRaw(): string {
  const div = new XMLElement("div",);
  div.append(new XMLBlob("<custom>x & y</custom>",),);
  return div.to_s();
}

/** `root(a, b)` usado pelos dois casos de XMLDocument. */
function docRoot(): XMLElement {
  const root = new XMLElement("root",);
  root.append(new XMLElement("a",),);
  root.append(new XMLElement("b",),);
  return root;
}

function xmlDocConcat(): string {
  const doc = new XMLDocument();
  doc.append(docRoot(),);
  doc.append(new XMLComment("nota",),);
  return doc.to_s();
}

function xmlDocWrite(): string {
  const doc = new XMLDocument();
  doc.append(docRoot(),);
  return doc.write(".",) ?? "";
}

function html5Head(): string {
  const doc = new HTMLDocument("html5",);
  const head = doc.generateHead("T", {}, null,);
  const body = new XMLElement("body",);
  body.append("Corpo",);
  head.append(body,);
  return doc.write(".",) ?? "";
}

function strictHeadMetaBlob(): string {
  const doc = new HTMLDocument("strict",);
  const head = doc.generateHead(
    "Relatório",
    { generator: "TaskJuggler", author: "Quem", },
    "<style>body{color:red}</style>",
  );
  head.append(new XMLElement("body",),);
  return doc.write(".",) ?? "";
}

/** Um builder por id do golden — espelho 1:1 das lambdas do Ruby. */
const builders: Record<string, () => string> = {
  empty_div: () => new XMLElement("div",).to_s(),
  self_closing_hr: () => new XMLElement("hr", {}, true,).to_s(),
  hr_no_flag: () => new XMLElement("hr",).to_s(),
  ctor_string_child: ctorStringChild,
  append_text: () =>
    (() => {
      const div = new XMLElement("div",);
      div.append("Hello",);
      return div.to_s();
    })(),
  append_child: appendChildTree,
  one_child_no_newline: () => ulWith(["item",],),
  two_children_indent: () => ulWith(["a", "b",],),
  text_and_child: textAndChild,
  attrs_sorted: () => new XMLElement("td", { z: "1", a: "2", m: "3", },).to_s(),
  attr_escaping: () =>
    new XMLElement(
      "a",
      {
        href: "http://e.com/?a=1&b=2",
        title: 'He said "hi"',
      },
    ).to_s(),
  text_escaping: () => {
    const p = new XMLElement("p",);
    p.append('a < b & c > d "e"',);
    return p.to_s();
  },
  nil_child_ignored: nilChildIgnored,
  set_attr_operator: setAttrOperator,
  xmltext_escape: () => new XMLText('<b>x & y</b> "q"',).to_s(0,),
  named_text: () =>
    new XMLNamedText("Tom & Jerry", "div", { id: "tj", },).to_s(),
  comment_plain: () => new XMLComment("nota",).to_s(0,),
  comment_canonicalized: () => new XMLComment("a--b",).to_s(0,),
  comment_in_element: commentInElement,
  blob_raw: blobRaw,
  blob_multiline_indent: () => new XMLBlob("line1\nline2\nline3",).to_s(2,),
  xml_doc_concat: xmlDocConcat,
  xml_doc_write: xmlDocWrite,
  html5_head: html5Head,
  strict_head_meta_blob: strictHeadMetaBlob,
};

function loadCases(): GoldenCase[] {
  const path = new URL("./html-xml.golden.json", import.meta.url,);
  const parsed = JSON.parse(Deno.readTextFileSync(path,),) as {
    cases: GoldenCase[];
  };
  return parsed.cases;
}

describe("html-xml golden (17.16)", () => {
  const cases = loadCases();

  it("tem pelo menos 25 casos", () => {
    assertEquals(cases.length >= 25, true, `${cases.length} casos`,);
  });

  it("todo caso do golden tem builder correspondente", () => {
    const missing = cases.filter((c,) => !builders[c.id]).map((c,) => c.id);
    assertEquals(missing, [],);
  });

  for (const c of cases) {
    it(c.id, () => {
      assertEquals(builders[c.id]!(), c.expected,);
    },);
  }
});
