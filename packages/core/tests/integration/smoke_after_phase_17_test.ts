/**
 * 17.17.7 / 17.17.10 — Smoke test pós-Fase 17 (HTML/XML/iCalendar/Painter).
 *
 * Fecha a fase provando quatro pontos:
 *  1. **HTMLDocument real** — `new HTMLDocument('html5')` serializa com
 *     `<!DOCTYPE html>` (o mínimo `html-shell` da Fase 12 foi apagado em
 *     17.13; ADR 038).
 *  2. **ICalendar real** — o `Journal` de `src/ical/` (substituído em 17.14)
 *     continua produzindo `BEGIN:VJOURNAL` pelo envelope público.
 *  3. **Journal da Fase 16 (ADR 029) intacto** — o alias `ICalJournal` protege
 *     o nome `Journal` do modelo de journal; os dois coexistem na mesma import.
 *  4. **17.17.10** — `RichTextElement.to_html()` devolve um `XMLElement` real
 *     (classe de `src/xml/`), não o `SimpleXMLElement` da Fase 12.
 *
 * @see docs/syntaxmesh/fases/fase-17-html-xml-tarefas.md (17.17)
 * @see docs/syntaxmesh/decisoes/038-substituicao-xml.md
 */
import { assert, assertEquals, } from "@std/assert";
import { describe, it, } from "@std/testing/bdd";
import { HTMLDocument, } from "../../src/html/html-document.ts";
import { XMLElement, } from "../../src/xml/xml-element.ts";
import { ICalendar, Journal as ICalJournal, } from "../../src/ical/mod.ts";
import { Journal, } from "../../src/model/journal.ts";
import { RichText, } from "../../src/richtext/rich-text.ts";
import { TjTime, } from "../../src/time/tj-time.ts";
// Versão da fonte única (`version.ts`, reexportada como `VERSION` pelo barril do
// pacote): o smoke não fixa o número para não quebrar a cada bump promovido por
// `scripts/tag-version.ts` (24.6.6).
import { VERSION, } from "../../src/mod.ts";

describe("Smoke test after Fase 17 (HTML/XML/iCalendar/Painter)", () => {
  it("HTMLDocument('html5') serializa o DOCTYPE html5 e o <html> real", () => {
    const doc = new HTMLDocument("html5",);
    const head = doc.generateHead("Título",);
    const body = new XMLElement("body",);
    body.append("Corpo",);
    head.append(body,);
    // to_s concatena os elementos na ordem do construtor (17.2/17.4).
    const html = doc.to_s();
    assert(html.includes("<!DOCTYPE html>",), html,);
    assert(
      !html.includes("<!DOCTYPE html PUBLIC",),
      "html5 não leva DTD XHTML",
    );
    assert(
      html.includes('<html lang="en" xml:lang="en">',),
      html,
    );
    assert(html.includes("<title>Título</title>",), html,);
    assert(html.includes("Corpo",), html,);
    assert(
      html.includes(
        `This file has been generated by syntaxmesh v${VERSION}`,
      ),
      html,
    );
  });

  it("ICalendar real (17.14) produz BEGIN:VJOURNAL pelo envelope público", () => {
    const ical = new ICalendar("proj",);
    new ICalJournal(
      ical,
      "j-1",
      "Nota do dia",
      TjTime.fromString("2026-01-10",),
    );
    const out = ical.to_s();
    // A serialização final passa por `foldLines` (17.5), que converte `\n` em
    // CRLF conforme a RFC 5545.
    assert(out.includes("BEGIN:VCALENDAR\r\n",), out,);
    assert(out.includes("BEGIN:VJOURNAL\r\n",), out,);
    assert(out.includes("SUMMARY:Nota do dia\r\n",), out,);
    assert(out.includes("END:VJOURNAL\r\n",), out,);
    assert(
      out.endsWith("END:VCALENDAR\r\n",),
      JSON.stringify(out.slice(-24,),),
    );
  });

  it("Journal da Fase 16 (modelo) segue intacto sob o alias ICalJournal", () => {
    // O `Journal` do topo do pacote é o modelo de journal (ADR 029) — sem
    // conflito com o componente iCalendar, que chega aliásado (17.14).
    const journal = new Journal();
    assertEquals(journal.entryList.length(), 0,);
    assert(ICalJournal.name === "Journal", ICalJournal.name,);
  });

  it("RichTextElement.to_html() devolve XMLElement real (17.17.10)", () => {
    const rt = new RichText("== Título ==\n\nisto é '''negrito'''.\n",);
    const rti = rt.generateIntermediateFormat();
    assert(rti !== null, "RTI deve ser produzido",);
    const html = rti!.to_html();
    assert(html !== null,);
    // O contrato é XMLElementLike; a instância concreta é o XMLElement real
    // de src/xml/ (port de XMLElement.rb), não o SimpleXMLElement da Fase 12.
    assert(html! instanceof XMLElement, html!.constructor.name,);
    assert(html!.toHTML().includes("<b>negrito</b>",), html!.toHTML(),);
    // Serializer real: <div>/<span> aninhados com tags de título.
    assert(html!.toHTML().includes("Título",), html!.toHTML(),);
  });
});
