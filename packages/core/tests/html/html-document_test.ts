/**
 * 17.4 — `HTMLDocument`.
 *
 * Todas as strings esperadas foram copiadas da saída literal do Ruby real
 * (`HTMLDocument.rb` + `HTMLElements.rb` + `XMLElement.rb` executados com
 * `AppConfig.appName = 'tj3'` / `version = '3.8.4'`), apenas trocando o nome
 * da aplicação pelos valores do nosso `AppConfig`.
 *
 * @see docs/taskjuggler/lib/taskjuggler/HTMLDocument.rb
 * @see docs/syntaxmesh/fases/fase-17-html-xml-tarefas.md (17.4)
 */

import { describe, it, } from "@std/testing/bdd";
import { assert, assertEquals, assertThrows, } from "@std/assert";

import { AppConfig, } from "../../src/app-config.ts";
import { HTMLDocument, } from "../../src/html/html-document.ts";
import { XMLElement, } from "../../src/xml/xml-element.ts";

const GENERATED =
  `<!-- This file has been generated by ${AppConfig.appName} v${AppConfig.version} -->\n`;

describe("HTMLDocument — doctype html5 (17.4.1.3–4)", () => {
  it("nasce com doctype + comentário + <html> sem <head>", () => {
    const doc = new HTMLDocument();
    assertEquals(
      doc.to_s(),
      `<!DOCTYPE html>${GENERATED}<html lang="en" xml:lang="en"></html>`,
    );
  });

  it("o default é html5: não emite prolog XML nem DTD", () => {
    const s = new HTMLDocument().to_s();
    assert(!s.includes("<?xml",), s,);
    assert(!s.includes("DOCTYPE html PUBLIC",), s,);
    assert(!s.includes("xmlns",), s,);
  });

  it("expõe o elemento <html> (`attr_reader :html`)", () => {
    const doc = new HTMLDocument();
    assertEquals(doc.html.name, "html",);
    assert(doc.html instanceof XMLElement,);
  });
});

describe("HTMLDocument — doctypes XHTML (17.4.1.5, 17.4.1.8)", () => {
  const url = "http://www.w3.org/TR/xhtml1/DTD";

  it("strict: prolog + DTD Strict + xmlns", () => {
    const doc = new HTMLDocument("strict",);
    assert(
      doc.to_s().startsWith(
        `<?xml version="1.0" encoding="UTF-8"?><!DOCTYPE html PUBLIC "-//W3C//DTD XHTML 1.0 Strict//EN" "${url}/xhtml1-strict.dtd">${GENERATED}<html lang="en" xml:lang="en" xmlns="http://www.w3.org/1999/xhtml">`,
      ),
      doc.to_s(),
    );
  });

  it("transitional: DTD Transitional", () => {
    assert(
      new HTMLDocument("transitional",).to_s().includes(
        `XHTML 1.0 Transitional//EN" "${url}/xhtml1-transitional.dtd">`,
      ),
    );
  });

  it("frameset: DTD Frameset", () => {
    assert(
      new HTMLDocument("frameset",).to_s().includes(
        `XHTML 1.0 Frameset//EN" "${url}/xhtml1-frameset.dtd">`,
      ),
    );
  });

  it("docType inválido levanta `Unsupported docType`", () => {
    assertThrows(
      () => new HTMLDocument("xhtml" as never,),
      Error,
      "Unsupported docType",
    );
  });
});

describe("HTMLDocument — construtor com bloco (17.4.1.6–7)", () => {
  it("o bloco entra ANTES do doctype (super(&block) é o primeiro passo)", () => {
    const doc = new HTMLDocument("html5", () => [
      new XMLElement("div",),
    ],);
    assertEquals(
      doc.to_s(),
      `<div></div><!DOCTYPE html>${GENERATED}<html lang="en" xml:lang="en"></html>`,
    );
  });

  it("comenta com o nome e a versão do AppConfig", () => {
    assert(
      new HTMLDocument().to_s().includes(
        `This file has been generated by ${AppConfig.appName} v${AppConfig.version}`,
      ),
    );
  });
});

describe("HTMLDocument#generateHead (17.4.2)", () => {
  it("monta title + os dois meta obrigatórios", () => {
    const doc = new HTMLDocument();
    doc.generateHead("My Title",);
    assertEquals(
      doc.to_s(),
      `<!DOCTYPE html>${GENERATED}<html lang="en" xml:lang="en"><head>\n` +
        `  <title>My Title</title>\n` +
        `  <meta content="text/html; charset=utf-8" http-equiv="Content-Type"/>\n` +
        `  <meta content="IE=9" http-equiv="X-UA-Compatible"/>\n` +
        ` </head></html>`,
    );
  });

  it("⚠️ devolve o <html>, não o <head> (XMLElement#<< devolve self)", () => {
    const doc = new HTMLDocument();
    assertEquals(doc.generateHead("T",), doc.html,);
  });

  it("acrescenta um <meta name/content> por par de metaTags, na ordem", () => {
    const doc = new HTMLDocument();
    doc.generateHead("T2", { generator: "TJ", robots: "noindex", },);
    assert(
      doc.to_s().includes(
        `  <meta content="IE=9" http-equiv="X-UA-Compatible"/>\n` +
          `  <meta content="TJ" name="generator"/>\n` +
          `  <meta content="noindex" name="robots"/>\n`,
      ),
      doc.to_s(),
    );
  });

  it("inclui o blob cru no fim do head, se houver", () => {
    const doc = new HTMLDocument();
    doc.generateHead("T2", {}, "<style>b{}</style>",);
    assert(doc.to_s().includes("<style>b{}</style>\n </head>",), doc.to_s(),);
  });

  it("sem blob não há linha extra", () => {
    const doc = new HTMLDocument();
    doc.generateHead("T2", {}, null,);
    assert(!doc.to_s().includes("<style",), doc.to_s(),);
  });

  it("anexa o head ao <html> do documento", () => {
    const doc = new HTMLDocument();
    doc.generateHead("Head Title",);
    assertEquals(doc.html.children.length, 1,);
    assertEquals(doc.html.children[0]?.name, "head",);
    assert(doc.to_s().includes("<title>Head Title</title>",),);
  });
});
