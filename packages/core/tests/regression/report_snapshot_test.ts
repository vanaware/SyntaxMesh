/**
 * 26.9.7 — Regression snapshot de relatório HTML (F21 wave 1).
 *
 * Fixa o HTML normalizado de um `taskreport` completo (parse → schedule →
 * `Report.generate(["html"])`, ADR 027 — saída em memória). Trechos voláteis
 * normalizados: o carimbo "Created on" do rodapé administrativo (`<NOW>`) e
 * a versão injetada no build (`<VER>`).
 *
 * @see docs/syntaxmesh/fases/fase-21-compatibilidade-qualidade-tarefas.md (26.9)
 */
import { assert, assertEquals, } from "@std/assert";
import { describe, it, } from "@std/testing/bdd";
import { parseProject, } from "../parser/parse-helper.ts";
import { TjTime, } from "../../src/time/tj-time.ts";
import { ReportContext, } from "../../src/reports/report-context.ts";
// Efeito colateral: registra as fábricas de conteúdo (TaskListRE, ...).
import "../../src/reports/mod.ts";
import type { Project, } from "../../src/model/project.ts";
import type { Report, } from "../../src/model/report.ts";
import { assertSnapshot, } from "./snapshot-io.ts";

const SOURCE = `project snap "Snapshot" "1.0" 2026-01-01 - 2026-03-31 {
  timezone "UTC"
  now 2026-01-15
}
resource dev "Dev"
task items "Work" {
  start 2026-01-05
  task t1 "Design" { effort 2d allocate dev }
  task t2 "Build" { effort 3d allocate dev depends !t1 }
}
taskreport plan "Plan" {
  formats html
  columns bsi, name, start, end
}
`;

/** Rodapé administrativo tem relógio real — único trecho volátil do HTML. */
const CREATED_ON =
  /Created on \d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} with SyntaxMesh/;
/** Versão é injetada no build (APP_VERSION) — normalizada como o oráculo. */
const GENERATED_BY = /generated by syntaxmesh v[^\n]*/;

describe("Report HTML regression snapshot (26.9.7)", () => {
  it("HTML normalizado do taskreport bate com o baseline", () => {
    TjTime.setTimeZone("UTC",);
    const out = parseProject(SOURCE,);
    assert(out.threw === null, `parse lançou: ${out.threw?.message}`,);
    assertEquals(out.messageIds, [], "parse com mensagens",);
    const project = out.result as Project;
    project.schedule();

    const report = (project.reports.toArray() as Report[])
      .find((r,) => r.id === "plan");
    assert(report !== undefined, "taskreport plan ausente",);
    project.reportContexts.push(new ReportContext(project, report,),);
    try {
      report.generate(["html",],);
    } finally {
      project.reportContexts.pop();
    }
    const html = report.output as string | null;
    assert(html !== null && html.length > 0, "HTML vazio",);
    assert(CREATED_ON.test(html,), "rodapé sem carimbo Created on",);
    assertSnapshot(
      "report-html.snap.txt",
      html
        .replace(CREATED_ON, "Created on <NOW> with SyntaxMesh",)
        .replace(GENERATED_BY, "generated by syntaxmesh v<VER>",),
    );
  });
});
