#!/usr/bin/env ruby
# frozen_string_literal: true
# encoding: UTF-8
#
# html-xml.rb — golden de XMLElement/XMLText/XMLComment/XMLBlob/XMLDocument/
# HTMLDocument (Fase 17.16).
#
# Oracle: monta as árvores/listas abaixo com a API real do Ruby e grava o
# `to_s`/`write('.')` de cada uma. O teste Deno (`html-xml_golden_test.ts`)
# constrói a mesma estrutura com as classes portadas (17.1–17.4, 17.12) e
# compara byte-a-byte, sem normalização alguma (a string é interna; os
# `\n`/espaços de indentação são a própria carga útil verificada).
#
# Casos (25): cobertura da serialização fiel —
#   XMLElement: vazio, vazio self-closing, void sem flag (<hr></hr>), texto via
#   construtor/append, 1 filho sem newline, 2+ filhos com newline+indent,
#   mistura texto+filho, attrs ordenados, escape de atributo (& e " → \"),
#   escape de texto (& < >), nil ignorado, name inválido (ArgumentError).
#   XMLText: escape puro. XMLNamedText: tag+texto. XMLComment: forma
#   `<!-- x -->\n` + indent e canonicalize `--`. XMLBlob: cru + re-indent.
#   XMLDocument: to_s concat, write('.') puts-style. HTMLDocument: docType
#   html5/strict com generateHead (title + metaTags + blob).
#
# @see docs/taskjuggler/lib/taskjuggler/{XMLElement,XMLDocument,HTMLDocument}.rb
# @see docs/syntaxmesh/fases/fase-17-html-xml-tarefas.md (17.16)

$LOAD_PATH.unshift(File.expand_path("../../docs/taskjuggler/lib", __dir__))
require "json"
require "stringio"
require "taskjuggler/XMLElement"
require "taskjuggler/XMLDocument"
require "taskjuggler/HTMLDocument"
require "taskjuggler/AppConfig"

XMLElement = TaskJuggler::XMLElement
XMLText = TaskJuggler::XMLText
XMLNamedText = TaskJuggler::XMLNamedText
XMLComment = TaskJuggler::XMLComment
XMLBlob = TaskJuggler::XMLBlob
XMLDocument = TaskJuggler::XMLDocument
HTMLDocument = TaskJuggler::HTMLDocument

# O comentário "generated by …" do HTMLDocument usa AppConfig.appName/version.
# Fixamos nos valores default do port (`packages/core/src/app-config.ts`) para
# que a comparação byte-a-byte do golden funcione sem normalização.
AppConfig.appName = "syntaxmesh"
AppConfig.version = "0.0.0"

$cases = []

def add(id, kind, spec, expected)
  $cases << { "id" => id, "kind" => kind, "spec" => spec,
              "expected" => expected }
end

def capture_stdout
  old = $stdout
  $stdout = StringIO.new
  yield
  $stdout.string
ensure
  $stdout = old
end

# ——— XMLElement ———

add("empty_div", "element", { "name" => "div" }, XMLElement.new('div').to_s)

add("self_closing_hr", "element",
    { "name" => "hr", "selfClosing" => true },
    XMLElement.new('hr', {}, true).to_s)

add("hr_no_flag", "element", { "name" => "hr" }, XMLElement.new('hr').to_s)

add("ctor_string_child", "element", { "name" => "p" },
    XMLElement.new('p') { 'Hello' }.to_s)

add("append_text", "element", { "name" => "div" },
    (lambda do
       div = XMLElement.new('div')
       div << 'Hello'
       div.to_s
     end.call))

add("append_child", "element", { "name" => "div" },
    (lambda do
       outer = XMLElement.new('div')
       inner = XMLElement.new('span')
       inner << 'oi'
       outer << inner
       outer.to_s
     end.call))

add("one_child_no_newline", "element", { "name" => "ul" },
    (lambda do
       ul = XMLElement.new('ul')
       li = XMLElement.new('li')
       li << 'item'
       ul << li
       ul.to_s
     end.call))

add("two_children_indent", "element", { "name" => "ul" },
    (lambda do
       ul = XMLElement.new('ul')
       %w[a b].each do |t|
         li = XMLElement.new('li')
         li << t
         ul << li
       end
       ul.to_s
     end.call))

add("text_and_child", "element", { "name" => "div" },
    (lambda do
       div = XMLElement.new('div')
       div << 'txt'
       b = XMLElement.new('b')
       b << 'bold'
       div << b
       div.to_s
     end.call))

add("attrs_sorted", "element", { "name" => "td" },
    XMLElement.new('td', { 'z' => '1', 'a' => '2', 'm' => '3' }).to_s)

add("attr_escaping", "element", { "name" => "a" },
    XMLElement.new('a', { 'href' => 'http://e.com/?a=1&b=2',
                          'title' => 'He said "hi"' }).to_s)

add("text_escaping", "element", { "name" => "p" },
    (lambda do
       p2 = XMLElement.new('p')
       p2 << 'a < b & c > d "e"'
       p2.to_s
     end.call))

add("nil_child_ignored", "element", { "name" => "div" },
    (lambda do
       div = XMLElement.new('div')
       div << nil
       div << 'ok'
       div.to_s
     end.call))

add("set_attr_operator", "element", { "name" => "img" },
    (lambda do
       img = XMLElement.new('img')
       img['src'] = 'a&amp;b.png'
       img['alt'] = 'quote " inside'
       img.to_s
     end.call))

# ——— XMLText / XMLNamedText / XMLComment / XMLBlob ———

add("xmltext_escape", "text", { "text" => '<b>x & y</b> "q"' },
    XMLText.new('<b>x & y</b> "q"').to_s(0))

add("named_text", "namedText",
    { "text" => 'Tom & Jerry', "name" => 'div', "attrs" => { "id" => "tj" } },
    XMLNamedText.new('Tom & Jerry', 'div', { 'id' => 'tj' }).to_s)

add("comment_plain", "comment", { "text" => 'nota' },
    XMLComment.new('nota').to_s(0))

add("comment_canonicalized", "comment", { "text" => 'a--b' },
    XMLComment.new('a--b').to_s(0))

add("comment_in_element", "commentInElement", { "text" => 'oi' },
    (lambda do
       div = XMLElement.new('div')
       div << XMLComment.new('oi')
       div << 'x'
       div.to_s
     end.call))

add("blob_raw", "blob", { "blob" => "<custom>x & y</custom>" },
    (lambda do
       div = XMLElement.new('div')
       div << XMLBlob.new("<custom>x & y</custom>")
       div.to_s
     end.call))

add("blob_multiline_indent", "blobIndent",
    { "blob" => "line1\nline2\nline3", "depth" => 2 },
    XMLBlob.new("line1\nline2\nline3").to_s(2))

# ——— XMLDocument / HTMLDocument ———

add("xml_doc_concat", "xmlDocument", {},
    (lambda do
      doc = XMLDocument.new
      root = XMLElement.new('root')
      c1 = XMLElement.new('a')
      c2 = XMLElement.new('b')
      root << c1
      root << c2
      doc << root
      doc << XMLComment.new('nota')
      doc.to_s
    end.call))

add("xml_doc_write", "xmlDocumentWrite", {},
    (lambda do
      doc = XMLDocument.new
      root = XMLElement.new('root')
      c1 = XMLElement.new('a')
      c2 = XMLElement.new('b')
      root << c1
      root << c2
      doc << root
      capture_stdout { doc.write('.') }
    end.call))

def html_doc(docType, title, metaTags, blob, extra)
  (lambda do
     doc = HTMLDocument.new(docType)
     head = doc.generateHead(title, metaTags, blob)
     extra.call(head, doc)
     capture_stdout { doc.write('.') }
   end).call
end

add("html5_head", "htmlDocument",
    { "docType" => "html5", "title" => "T", "metaTags" => {},
      "blob" => nil },
    html_doc(:html5, 'T', {}, nil, lambda { |head, doc|
      body = XMLElement.new('body')
      body << 'Corpo'
      head << body
    }))

add("strict_head_meta_blob", "htmlDocument",
    { "docType" => "strict", "title" => "Relatório",
      "metaTags" => { "generator" => "TaskJuggler", "author" => "Quem" },
      "blob" => '<style>body{color:red}</style>' },
    html_doc(:strict, 'Relatório',
             { 'generator' => 'TaskJuggler', 'author' => 'Quem' },
             '<style>body{color:red}</style>',
             lambda { |head, doc|
               head << XMLElement.new('body')
             }))

puts JSON.generate({ "cases" => $cases })
